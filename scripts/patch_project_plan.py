def _eol_of(ln):
    return '\r\n' if ln.endswith('\r\n') else '\n'


def _to_crlf(body, eol):
    return body.replace('\r\n', '\n').replace('\n', eol)


def main():
    with open(PATH, encoding='utf-8', newline='') as f:
        orig = f.read()

    # ---- 第一遍：sub 替换。先做，因为它的锚点最脆弱，且不涉及行号 ----
    text = orig
    failed, applied = [], []
    subs = [e for e in E if e[2] == 'sub']
    lins = [e for e in E if e[2] != 'sub']

    for tag, desc, mode, key, new, n in subs:
        cnt = text.count(key)
        if cnt != n:
            failed.append((tag, desc, cnt, n, key[:80]))
            continue
        text = text.replace(key, new, n)
        applied.append((tag, desc))

    # ---- 第二遍：line / after 整行操作 ----
    lines = text.splitlines(keepends=True)
    replaced = set()
    inserted_after = {}

    for tag, desc, mode, key, new, n in lins:
        hits = [i for i, ln in enumerate(lines) if key in ln and i not in replaced]
        if len(hits) != n:
            failed.append((tag, desc, len(hits), n, key[:80]))
            continue
        for i in hits:
            eol = _eol_of(lines[i])
            body = _to_crlf(new, eol)
            if mode == 'line':
                lines[i] = body + eol
            else:
                inserted_after[i] = body + eol
            replaced.add(i)
        applied.append((tag, desc))

    if failed:
        print('!! 有替换未匹配，已中止，未写入文件')
        for tag, desc, cnt, n, head in failed:
            print('  [%s] %s' % (tag, desc))
            print('       期望 %d 次，实际 %d 次' % (n, cnt))
            print('       锚点: %s...' % head)
        return 1

    out = []
    for i, ln in enumerate(lines):
        out.append(ln)
        if i in inserted_after:
            out.append(inserted_after[i])
    text = ''.join(out)

    print('全部 %d 条替换成功：' % len(applied))
    for tag, desc in applied:
        print('  [%s] %s' % (tag, desc))

    if not os.path.exists(BACKUP):
        with open(BACKUP, 'w', encoding='utf-8', newline='') as f:
            f.write(orig)
        print('\n已留原始备份: %s' % BACKUP)
    else:
        print('\n备份已存在，未覆盖: %s' % BACKUP)

    with open(PATH, 'w', encoding='utf-8', newline='') as f:
        f.write(text)

    print('\n写入完成: %s' % PATH)
    print('  字符数 %s -> %s' % (format(len(orig), ','), format(len(text), ',')))
    print('  行数 %s -> %s（新增 %s 行）' % (
        format(orig.count('\r\n'), ','), format(text.count('\r\n'), ','),
        text.count('\r\n') - orig.count('\r\n')))
    return 0


if __name__ == '__main__':
    sys.exit(main())
